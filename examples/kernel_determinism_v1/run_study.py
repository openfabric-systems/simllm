def decode_record(requests: int, *, context_length: int = 64) -> StepRecord:
    """One decode step with ``requests`` single-token continuations."""

    scheduled = [
        ScheduledRequest(
            f"d{index}",
            RequestPhase.DECODE,
            1,
            context_length=context_length,
        )
        for index in range(requests)
    ]
    return StepRecord(
        step_index=0,
        virtual_time_ps=0,
        scheduled=scheduled,
        num_sampled=requests,
        sampled_request_ids=[request.request_id for request in scheduled],
    )


def prefill_record(chunk_tokens: int) -> StepRecord:
    """One prefill step of a single ``chunk_tokens``-token chunk."""

    scheduled = [
        ScheduledRequest(
            "p0",
            RequestPhase.PREFILL,
            chunk_tokens,
            context_length=chunk_tokens,
        )
    ]
    return StepRecord(
        step_index=0,
        virtual_time_ps=0,
        scheduled=scheduled,
        num_sampled=1,
        sampled_request_ids=["p0"],
    )


