#!/usr/bin/env python3
"""kernel_determinism_v1: the kernel-time determinism contract.

Harness for the freeze in ``expectations.md``. It measures the observable
consequences of the maintainer's 2026-08-18 ruling that a compute kernel's
service time is a deterministic constant with no tail, a pure function of
kernel family, phase, token and shape inputs, and the architecture profile.

Evidence classes are kept apart and are never added into one total:

``fatal_guard``
    Voids the run when violated. Never reported as a fraction. Determinism of a
    deterministic function is entailed by its construction, so the repeat and
    fresh-instance rows live here rather than in the scored denominator.
``control``
    Proves a guard or a scored row is discriminating. A control that fails to
    fail is itself a finding.
``scored``
    The eight genuine-risk instances of the freeze, each an exact integer
    predicted before the implementation existed.
``derived``
    Arithmetic over rows already scored. Reported, never counted.
``observation``
    Raw configuration facts. Assert nothing.

Run it with no arguments to regenerate ``results.json`` beside this file, or
with ``--check`` to require the regenerated bytes to equal the committed
artifact.
"""

