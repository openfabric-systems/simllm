@dataclass(frozen=True)
class Row:
    row_id: str
    evidence_class: str
    family: str
    case: str
    expected: Any
    measured: Any

    @property
    def passed(self) -> bool:
        return self.expected == self.measured

    @property
    def status(self) -> str:
        if self.evidence_class == OBSERVATION:
            return "REPORTED"
        return "PASS" if self.passed else "FAIL"

    def to_json(self) -> dict[str, Any]:
        return {
            "id": self.row_id,
            "evidence_class": self.evidence_class,
            "family": self.family,
            "case": self.case,
            "expected": self.expected,
            "measured": self.measured,
            "status": self.status,
        }


