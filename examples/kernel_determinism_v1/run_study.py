def summarize(rows: list[Row]) -> dict[str, Any]:
    guards = [row for row in rows if row.evidence_class == FATAL_GUARD]
    controls = [row for row in rows if row.evidence_class == CONTROL]
    scored = [row for row in rows if row.evidence_class == SCORED]
    derived = [row for row in rows if row.evidence_class == DERIVED]
    violated = [row.row_id for row in guards if not row.passed]
    return {
        "fatal_guards": len(guards),
        "fatal_guards_violated": violated,
        "void": bool(violated),
        "controls": len(controls),
        "controls_failed": [row.row_id for row in controls if not row.passed],
        "scored_total": len(scored),
        "scored_passed": sum(1 for row in scored if row.passed),
        "scored_failed": [row.row_id for row in scored if not row.passed],
        "derived_reported": len(derived),
        "derived_failed": [row.row_id for row in derived if not row.passed],
    }


def build_payload() -> dict[str, Any]:
    rows = collect_rows()
    return {
        "schema": SCHEMA,
        "freeze": FREEZE,
        "fixtures": {
            "roofline_geometry": _plain(model_dims()),
            "roofline_gpu": _plain(gpu_spec()),
            "roofline_efficiency": EFFICIENCY,
            "host_profile": "ideal",
            "mechanistic_source": "examples/gpu_task_mix/run_gpu_task_mix.py",
            "mechanistic_transaction_bytes": MECHANISTIC_TRANSACTION_BYTES,
            "mechanistic_hbm_latency_cycles": TASK_MIX.HBM_LATENCY,
            "repeats": REPEATS,
        },
        "rows": [row.to_json() for row in rows],
        "summary": summarize(rows),
    }


def render(payload: dict[str, Any]) -> str:
    return json.dumps(payload, indent=2, sort_keys=False) + "\n"


def transcript(payload: dict[str, Any]) -> str:
    lines = ["kernel_determinism_v1", f"freeze: {payload['freeze']}", ""]
    for row in payload["rows"]:
        lines.append(
            f"{row['status']:8s} {row['evidence_class']:12s} {row['id']:10s} "
            f"{row['family']} [{row['case']}]"
        )
    summary = payload["summary"]
    lines.append("")
    if summary["void"]:
        lines.append(f"VOID: fatal guards violated: {summary['fatal_guards_violated']}")
    else:
        lines.append(f"all {summary['fatal_guards']} fatal guards held")
    lines.append(
        f"scored {summary['scored_passed']} of {summary['scored_total']}"
        f"; controls {summary['controls'] - len(summary['controls_failed'])}"
        f" of {summary['controls']}"
        f"; derived rows reported: {summary['derived_reported']}"
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="require the regenerated artifact to equal the committed bytes",
    )
    parser.add_argument("--out", type=Path, default=RESULTS)
    args = parser.parse_args(argv)

    payload = build_payload()
    rendered = render(payload)
    print(transcript(payload), end="")

    if args.check:
        if not args.out.exists():
            print(f"missing committed artifact {args.out}")
            return 1
        committed = args.out.read_bytes()
        if committed != rendered.encode("utf-8"):
            print(f"artifact {args.out} does not reproduce byte for byte")
            return 1
    else:
        args.out.write_text(rendered, encoding="utf-8", newline="\n")

    summary = payload["summary"]
    if summary["void"] or summary["controls_failed"] or summary["scored_failed"]:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
