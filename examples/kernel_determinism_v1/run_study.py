def _roofline_estimate(provider: RooflineProvider, record: StepRecord, sampled: int):
    return provider.estimate(step_kernel(model_dims(), record, sampled), gpu_spec())


def guard_repeat_determinism(rows: list[Row]) -> None:
    """G1: repeated estimates through one instance are one byte string."""

    provider = roofline()
    for row_id, label, factory, sampled in ROOFLINE_CELLS:
        record = factory()
        streams = {
            canonical(_roofline_estimate(provider, record, sampled))
            for _ in range(REPEATS)
        }
        rows.append(
            Row(
                f"G1-{row_id}",
                FATAL_GUARD,
                "repeat determinism, roofline",
                f"{label},repeats={REPEATS}",
                1,
                len(streams),
            )
        )
    for row_id, bandwidth, sm_count, _ in MECHANISTIC_CELLS:
        model = mechanistic_model(hbm_bandwidth=bandwidth, sm_count=sm_count)
        launch = mechanistic_launch()
        streams = {canonical(model.estimate(launch)) for _ in range(REPEATS)}
        rows.append(
            Row(
                f"G1-{row_id}",
                FATAL_GUARD,
                "repeat determinism, mechanistic",
                f"bw={bandwidth},sms={sm_count},repeats={REPEATS}",
                1,
                len(streams),
            )
        )


def guard_fresh_instance_determinism(rows: list[Row]) -> None:
    """G2: a freshly built provider produces the same byte string."""

    for row_id, label, factory, sampled in ROOFLINE_CELLS:
        record = factory()
        first = canonical(_roofline_estimate(roofline(), record, sampled))
        second = canonical(_roofline_estimate(roofline(), factory(), sampled))
        rows.append(
            Row(
                f"G2-{row_id}",
                FATAL_GUARD,
                "fresh-instance determinism, roofline",
                label,
                first.decode("utf-8"),
                second.decode("utf-8"),
            )
        )
    for row_id, bandwidth, sm_count, _ in MECHANISTIC_CELLS:
        first = canonical(
            mechanistic_model(
                hbm_bandwidth=bandwidth, sm_count=sm_count
            ).estimate(mechanistic_launch())
        )
        second = canonical(
            mechanistic_model(
                hbm_bandwidth=bandwidth, sm_count=sm_count
            ).estimate(mechanistic_launch())
        )
        rows.append(
            Row(
                f"G2-{row_id}",
                FATAL_GUARD,
                "fresh-instance determinism, mechanistic",
                f"bw={bandwidth},sms={sm_count}",
                first.decode("utf-8"),
                second.decode("utf-8"),
            )
        )


def guard_host_identity(rows: list[Row]) -> None:
    """G3: the ideal host profile adds exactly zero to every R cell."""

    ideal = HostInitiationModel.ideal()
    provider = roofline()
    for row_id, label, factory, sampled in ROOFLINE_CELLS:
        estimate = _roofline_estimate(provider, factory(), sampled)
        composed = ideal.represented_estimate(estimate, gpu_spec())
        rows.append(
            Row(
                f"G3-{row_id}",
                FATAL_GUARD,
                "ideal host profile is the exact identity",
                label,
                [estimate.duration_ps, 0],
                [composed.duration_ps, composed.exposed_ps],
            )
        )


