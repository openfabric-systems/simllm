#: modules whose import into a service path would make a duration nondeterministic
NONDETERMINISM_SOURCES = (
    "random",
    "secrets",
    "time",
    "datetime",
    "uuid",
    "os",
    "socket",
    "platform",
    "getpass",
    "tempfile",
    "numpy.random",
)


def imported_modules(path: Path) -> set[str]:
    """Top-level module names imported by one source file, from its AST."""

    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                found.add(alias.name)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            found.add(node.module)
    return found


def compute_module_paths() -> list[Path]:
    return sorted((REPO_ROOT / "simllm" / "compute").glob("*.py"))


def nondeterminism_audit(paths: Iterable[Path] | None = None) -> dict[str, list[str]]:
    """Every audited module that imports a nondeterminism source.

    ``paths`` defaults to the whole ``simllm/compute`` package. It is a
    parameter so the control can hand the audit a file that really does import
    one, which is the only way to know the audit is reading imports rather than
    returning an empty dictionary.
    """

    offenders: dict[str, list[str]] = {}
    for path in compute_module_paths() if paths is None else paths:
        hits = sorted(
            name
            for name in imported_modules(path)
            if name in NONDETERMINISM_SOURCES
            or any(name.startswith(f"{source}.") for source in NONDETERMINISM_SOURCES)
        )
        if hits:
            offenders[path.name] = hits
    return offenders


#: parameter-name fragments that would make a price depend on who asked
IDENTITY_PARAMETERS = ("rank", "worker", "adapter", "device_index", "gpu_index", "gpu_id")


#: modules that define a shipped ``ComputeProvider``. They are imported before
#: the sweep so the subclass set is complete no matter what else the process has
#: loaded, and the sweep keeps only ``simllm.`` classes so a study's own throwaway
#: fixture provider cannot change what this audit covers. Without both halves the
#: audited set depends on import order, which the artifact byte lock caught.
FIRST_PARTY_PROVIDER_MODULES = (
    "simllm.compute.provider",
    "simllm.compute.gpu_model",
    "simllm.adapters.sglang.host",
)


def first_party_providers() -> list[type]:
    """Every shipped ``ComputeProvider`` subclass, in a stable order."""

    for module in FIRST_PARTY_PROVIDER_MODULES:
        importlib.import_module(module)
    found: dict[str, type] = {}
    pending = list(ComputeProvider.__subclasses__())
    while pending:
        subclass = pending.pop()
        pending.extend(subclass.__subclasses__())
        if subclass.__module__.startswith("simllm."):
            found[f"{subclass.__module__}.{subclass.__qualname__}"] = subclass
    return [found[key] for key in sorted(found)]


def pricing_entry_points() -> dict[str, Any]:
    """Every callable that turns work into a duration."""

    entries: dict[str, Any] = {
        "ComputeProvider.estimate": ComputeProvider.estimate,
        "ComputeProvider.estimate_layers": ComputeProvider.estimate_layers,
        "SmSchedulerModel.estimate": SmSchedulerModel.estimate,
        "SmSchedulerModel.estimate_concurrent": SmSchedulerModel.estimate_concurrent,
        "transformer.step_kernel": step_kernel,
        "transformer.step_kernels": step_kernels,
        "transformer.estimate_step_latency_ps": estimate_step_latency_ps,
        "HostInitiationModel.represented_estimate": (
            HostInitiationModel.represented_estimate
        ),
    }
    for subclass in first_party_providers():
        key = f"{subclass.__name__}.estimate"
        if key in entries:
            key = f"{subclass.__module__}.{subclass.__qualname__}.estimate"
        entries[key] = subclass.estimate
    return entries


def identity_parameter_audit(
    entries: dict[str, Any] | None = None,
) -> dict[str, list[str]]:
    """Every pricing entry point that accepts a caller-identity parameter.

    ``entries`` defaults to :func:`pricing_entry_points`. It is a parameter for
    the same reason the import audit takes paths: the control needs to hand the
    audit a signature that really does key on a rank.
    """

    offenders: dict[str, list[str]] = {}
    for name, function in sorted(
        (pricing_entry_points() if entries is None else entries).items()
    ):
        hits = [
            parameter
            for parameter in inspect.signature(function).parameters
            if any(fragment in parameter.lower() for fragment in IDENTITY_PARAMETERS)
        ]
        if hits:
            offenders[name] = hits
    return offenders


