def _load(name: str, relative: str) -> Any:
    """Load an accepted study as a module so its own fixtures are used."""

    path = REPO_ROOT / relative
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load accepted study {relative}")
    module = importlib.util.module_from_spec(spec)
    # Register before executing: a loaded study defines dataclasses, and
    # dataclasses resolves annotations through sys.modules while the body runs.
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


